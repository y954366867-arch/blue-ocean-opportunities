import {randomUUID} from 'node:crypto';
import {writeFileSync} from 'node:fs';
import {list,save} from '../lib/db';
import {summarize,syncQueue} from '../lib/content-analysis';
import {refresh,ensureInspirations,publicCategory,type CategoryRun} from '../lib/category-v4';
const runs=list<CategoryRun>('category-run').filter(r=>r.selection.categoryId==='bags'&&r.selection.days===60);
const base=runs.find(r=>r.qualifiedIds.length>=4&&r.notes.length>=303);
if(!base) throw Error('没有可复用的完整推荐缓存');
const latest=runs[0];
const r=structuredClone(base);
const at=Date.now();
r.id=randomUUID();r.parentId=latest.id;r.createdAt=new Date().toISOString();r.cancelRequested=false;r.mode='analyze-existing';r.status='running';r.timings=[];r.directions=[];r.queries=[];
const ids=new Set(r.notes.map(n=>n.id));
r.notes.push(...latest.notes.filter(n=>!ids.has(n.id)));
syncQueue(r);refresh(r);
await summarize(r,new AbortController().signal,Date.now()+180000,()=>save('category-run',r.id,r));
ensureInspirations(r);r.status='partial';r.elapsedMs=Date.now()-at;r.updatedAt=new Date().toISOString();save('category-run',r.id,r);
writeFileSync('reports/inspiration-expression-v8.json',JSON.stringify(publicCategory(r),null,2));
console.log(JSON.stringify({ms:r.elapsedMs,cards:r.directions.map(d=>({name:d.name,count:d.noteIds.length,status:d.summaryStatus,creative:d.creative})),pending:r.unanalyzedIds?.length,queries:r.queries,warnings:r.warnings.slice(-4)}));
